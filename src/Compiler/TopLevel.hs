-- | Generate a C ABI wrapper that converts between C i64 and Flux %Value
generateCABIWrapper :: String -> [String] -> Compiler ()
generateCABIWrapper name params = do
  let cParamList = intercalate ", " [("i64 %p" ++ show i) | i <- [0..length params - 1]]
      boxingCode = concat [ [ "  %pbox" ++ show i ++ " = call %Value @box_int(i64 %p" ++ show i ++ ")"
                            , "  %pboxptr" ++ show i ++ " = alloca %Value"
                            , "  store %Value %pbox" ++ show i ++ ", %Value* %pboxptr" ++ show i
                            ] | i <- [0..length params - 1] ]
      callArgs = intercalate ", " [("%Value* %pboxptr" ++ show i) | i <- [0..length params - 1]]
      callLine = if null params
                 then "  %res = call %Value @__flux_" ++ name ++ "()"
                 else "  %res = call %Value @__flux_" ++ name ++ "(" ++ callArgs ++ ")"
  
  modify $ \s -> s { csFunctions = csFunctions s ++
    [ "define i64 @" ++ name ++ "(" ++ cParamList ++ ") {"
    , "entry:"
    ] ++ boxingCode ++ 
    [ callLine
    , "  %raw = call i64 @unbox_int(%Value %res)"
    , "  ret i64 %raw"
    , "}"
    , ""
    ] }

compileProgramToFile :: Program -> FilePath -> Bool -> IO ()
compileProgramToFile prog path cabi =
  let ir = if cabi then compileProgramCABI prog else compileProgram prog
  in writeFile path ir

